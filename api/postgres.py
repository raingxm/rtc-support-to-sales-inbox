from typing import Sequence

from psycopg import Connection, IsolationLevel, connect
from psycopg.types.json import Json

from api.inbox import (
    STOPPED_WAITING, CustomerMessage, Owner, PendingReason, Reply, Ticket, TicketContent, TicketNotFound,
    Triage,
)


_CREATE_TICKETS = """
CREATE TABLE IF NOT EXISTS rtc_tickets (
    number bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1043) PRIMARY KEY,
    id text GENERATED ALWAYS AS ('RTC-' || number::text) STORED UNIQUE,
    sample_order integer UNIQUE,
    content json NOT NULL
)
"""

_CREATE_HANDOFFS = """
CREATE TABLE IF NOT EXISTS rtc_handoffs (
    ticket_number bigint PRIMARY KEY REFERENCES rtc_tickets(number),
    owner text,
    confirmed_by text,
    withdrawn_by text
)
"""

_SELECT_TICKETS = """
SELECT t.id, t.sample_order, t.content, h.owner, h.confirmed_by, h.withdrawn_by
FROM rtc_tickets AS t
LEFT JOIN rtc_handoffs AS h ON h.ticket_number = t.number
"""

_TicketRow = tuple[str, int | None, dict[str, object], str | None, str | None, str | None]


def _ticket(row: _TicketRow) -> Ticket:
    ticket_id, sample_order, content, owner, confirmed_by, withdrawn_by = row
    engineer_assigned = owner is not None
    return Ticket.model_validate({
        **content,
        "id": ticket_id,
        "origin": "sample" if sample_order is not None else "live",
        "handoff": {"owner": owner} if engineer_assigned else None,
        "confirmed_by": confirmed_by,
        "withdrawn_by": None if engineer_assigned else withdrawn_by,
    })


class PostgresTicketStore:
    def __init__(self, database_url: str) -> None:
        self._database_url = database_url

    def _connect(self) -> Connection:
        connection = connect(self._database_url, connect_timeout=5)
        connection.isolation_level = IsolationLevel.READ_COMMITTED
        return connection

    def seed(self, samples: Sequence[Ticket]) -> None:
        with self._connect() as connection:
            connection.execute("SELECT pg_advisory_xact_lock(7492060001042)")
            connection.execute(_CREATE_TICKETS)
            connection.execute(_CREATE_HANDOFFS)
            connection.execute("ALTER TABLE rtc_handoffs ADD COLUMN IF NOT EXISTS confirmed_by text")
            connection.execute("ALTER TABLE rtc_handoffs ADD COLUMN IF NOT EXISTS withdrawn_by text")
            connection.execute("ALTER TABLE rtc_handoffs ALTER COLUMN owner DROP NOT NULL")
            for position, sample in enumerate(samples):
                connection.execute(
                    """
                    INSERT INTO rtc_tickets (number, sample_order, content)
                    VALUES (%s, %s, %s)
                    ON CONFLICT (number) DO NOTHING
                    """,
                    (
                        int(sample.id.removeprefix("RTC-")),
                        position,
                        Json(sample.model_dump(mode="json", include=set(TicketContent.model_fields))),
                    ),
                )

    def list_tickets(self) -> list[Ticket]:
        with self._connect() as connection:
            rows = connection.execute(
                _SELECT_TICKETS + "ORDER BY t.sample_order NULLS LAST, t.number"
            ).fetchall()
            return [_ticket(row) for row in rows]

    def get(self, ticket_id: str) -> Ticket | None:
        with self._connect() as connection:
            row = connection.execute(_SELECT_TICKETS + "WHERE t.id = %s", (ticket_id,)).fetchone()
            return None if row is None else _ticket(row)

    def append(self, content: TicketContent) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                "INSERT INTO rtc_tickets (content) VALUES (%s) RETURNING id, sample_order, content, NULL, NULL, NULL",
                (Json(content.model_dump(mode="json")),),
            ).fetchone()
            assert row is not None
            return _ticket(row)

    def _write(self, connection: Connection, ticket: Ticket) -> Ticket:
        connection.execute(
            "UPDATE rtc_tickets SET content = %s WHERE id = %s",
            (Json(ticket.model_dump(mode="json", include=set(TicketContent.model_fields))), ticket.id),
        )
        stored = connection.execute(_SELECT_TICKETS + "WHERE t.id = %s", (ticket.id,)).fetchone()
        assert stored is not None
        return _ticket(stored)

    def append_message(self, ticket_id: str, message: CustomerMessage) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                _SELECT_TICKETS + "WHERE t.id = %s FOR UPDATE OF t",
                (ticket_id,),
            ).fetchone()
            if row is None:
                raise TicketNotFound(ticket_id)
            latest = _ticket(row)
            return self._write(connection, latest.model_copy(update={"messages": (*latest.messages, message)}))

    def drop_last_message(self, ticket_id: str, message_count: int) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                _SELECT_TICKETS + "WHERE t.id = %s FOR UPDATE OF t",
                (ticket_id,),
            ).fetchone()
            if row is None:
                raise TicketNotFound(ticket_id)
            latest = _ticket(row)
            if len(latest.messages) != message_count:
                return latest
            return self._write(connection, latest.model_copy(update={"messages": latest.messages[:-1]}))

    def delete(self, ticket_id: str) -> None:
        with self._connect() as connection:
            connection.execute("DELETE FROM rtc_tickets WHERE id = %s", (ticket_id,))

    def apply_analysis(self, ticket_id: str, triage: Triage, title: str, message_count: int) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                _SELECT_TICKETS + "WHERE t.id = %s FOR UPDATE OF t",
                (ticket_id,),
            ).fetchone()
            if row is None:
                raise TicketNotFound(ticket_id)
            latest = _ticket(row)
            if latest.handoff is not None or len(latest.messages) != message_count:
                return latest
            updated = latest.model_copy(update={"triage": triage, "title": title, "pending_reason": None})
            connection.execute(
                "UPDATE rtc_tickets SET content = %s WHERE id = %s",
                (Json(updated.model_dump(mode="json", include=set(TicketContent.model_fields))), ticket_id),
            )
            stored = connection.execute(_SELECT_TICKETS + "WHERE t.id = %s", (ticket_id,)).fetchone()
        assert stored is not None
        return _ticket(stored)

    def land_analysis(
        self,
        ticket_id: str,
        message_count: int,
        reply_count: int,
        triage: Triage,
        title: str,
        reply: Reply | None,
        pending_reason: PendingReason | None,
    ) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                _SELECT_TICKETS + "WHERE t.id = %s FOR UPDATE OF t",
                (ticket_id,),
            ).fetchone()
            if row is None:
                raise TicketNotFound(ticket_id)
            latest = _ticket(row)
            if len(latest.messages) != message_count:
                return latest
            spoken = any(reply.author for reply in latest.replies)
            update: dict[str, object] = {}
            if latest.handoff is None and not spoken:
                update["triage"] = triage
                update["title"] = title
            if reply is not None and not spoken and len(latest.replies) == reply_count:
                update["replies"] = (*latest.replies, reply)
                update["pending_reason"] = pending_reason
            if not update:
                return latest
            return self._write(connection, latest.model_copy(update=update))

    def mark_stopped_waiting(self, ticket_id: str, message_count: int, reply_count: int) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                _SELECT_TICKETS + "WHERE t.id = %s FOR UPDATE OF t",
                (ticket_id,),
            ).fetchone()
            if row is None:
                raise TicketNotFound(ticket_id)
            latest = _ticket(row)
            if len(latest.messages) != message_count or len(latest.replies) != reply_count:
                return latest
            return self._write(connection, latest.model_copy(update={"pending_reason": STOPPED_WAITING}))

    def add_reply(self, ticket_id: str, reply: Reply) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                _SELECT_TICKETS + "WHERE t.id = %s FOR UPDATE OF t",
                (ticket_id,),
            ).fetchone()
            if row is None:
                raise TicketNotFound(ticket_id)
            latest = _ticket(row)
            return self._write(connection, latest.model_copy(update={
                "replies": (*latest.replies, reply),
                "pending_reason": None,
                "taken_over": True,
            }))

    def hand_back(self, ticket_id: str, handed_back_by: str) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                _SELECT_TICKETS + "WHERE t.id = %s FOR UPDATE OF t",
                (ticket_id,),
            ).fetchone()
            if row is None:
                raise TicketNotFound(ticket_id)
            latest = _ticket(row)
            return self._write(connection, latest.hand_back(handed_back_by))

    def confirm_handoff(self, ticket_id: str, owner: Owner, confirmed_by: str) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                _SELECT_TICKETS + "WHERE t.id = %s FOR UPDATE OF t",
                (ticket_id,),
            ).fetchone()
            if row is None:
                raise TicketNotFound(ticket_id)
            ticket = _ticket(row)
            assigned = ticket.assign_handoff(owner, confirmed_by)
            if assigned is ticket:
                return ticket

            connection.execute(
                """
                INSERT INTO rtc_handoffs (ticket_number, owner, confirmed_by, withdrawn_by)
                SELECT number, %s, %s, NULL FROM rtc_tickets WHERE id = %s
                ON CONFLICT (ticket_number) DO UPDATE
                SET owner = EXCLUDED.owner,
                    confirmed_by = EXCLUDED.confirmed_by,
                    withdrawn_by = NULL
                WHERE rtc_handoffs.owner IS NULL
                """,
                (owner, confirmed_by, ticket_id),
            )
            confirmed = connection.execute(_SELECT_TICKETS + "WHERE t.id = %s", (ticket_id,)).fetchone()
            assert confirmed is not None
            return _ticket(confirmed)

    def withdraw_handoff(self, ticket_id: str, withdrawn_by: str) -> Ticket:
        with self._connect() as connection:
            row = connection.execute(
                _SELECT_TICKETS + "WHERE t.id = %s FOR UPDATE OF t",
                (ticket_id,),
            ).fetchone()
            if row is None:
                raise TicketNotFound(ticket_id)
            ticket = _ticket(row)
            ticket.withdraw_handoff(withdrawn_by)
            connection.execute(
                """
                UPDATE rtc_handoffs
                SET owner = NULL, withdrawn_by = %s
                WHERE ticket_number = (SELECT number FROM rtc_tickets WHERE id = %s)
                """,
                (withdrawn_by, ticket_id),
            )
            stored = connection.execute(_SELECT_TICKETS + "WHERE t.id = %s", (ticket_id,)).fetchone()
            assert stored is not None
            return _ticket(stored)
